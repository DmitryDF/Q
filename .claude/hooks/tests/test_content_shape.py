"""The content-shape gate — is what we read the document, or a reference to one?

content-shape-gate D3 / plan action A3.

Three altitudes, and the split is the same one the sibling admission suites use:

* **Predicate level** — the pure function, driven on the REAL bytes of a real
  synced-drive placeholder taken off this machine and on the real git-LFS pointer
  form, plus the must-NOT-refuse cases at BOTH error directions.
* **Port level** — both path-shaped adapters driven THROUGH ``admit()``, never
  called directly, asserting the refusal reaches a RECORDED degradation rather
  than merely being returned, and that a non-path-shaped kind inherits nothing.
* **Caller level** — the refusal renders into the report body through the same
  channel the PDF refusal already uses, because to a person it is the same event.

**Why the must-not-refuse cases matter more than the refusals.** The refusals are
easy; the failure this slice could ship is over-refusal. Both directions are
guarded by DIFFERENT mechanisms and each has its own test: a ~50-byte genuine
note is below any conceivable size cap and survives only because every shape test
names a concrete shape, while a large JSON legitimately carrying ``doc_id``
matches a shape exactly and survives only because of the cap. A suite testing one
direction would pass with a predicate that is wrong in the other.
"""

