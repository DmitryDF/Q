def test_emptiness_is_not_subject_to_the_shape_catalog():
    """Emptiness is a UNIVERSAL test, not a signature — which is what makes the
    live case fully covered while placeholder coverage is limited to shapes the
    catalog names. If it were a `Shape` it would sit behind the size cap, which
    is harmless today and would silently stop being harmless if the cap moved."""
    assert cs.REASON_EMPTY not in [s.reason for s in cs.SHAPES]
    assert cs.not_the_document("") == cs.REASON_EMPTY


