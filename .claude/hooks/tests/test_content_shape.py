# The REAL bytes of a real placeholder off this machine — 180 bytes, recorded in
# `research-source-adapters-20260829002225_DISCOVERY_WIP_4b796aef.md` §2. The
# document id is elided; nothing in the predicate reads its value.
REAL_DRIVE_STUB = (
    '{"": "WARNING! DO NOT EDIT THIS FILE! ANY CHANGES MADE WILL BE LOST!", '
    '"doc_id": "1QvMu0jYaKQ3xnR8pLd2fVhT7wZmB4cXeN6sGiUyOoAk", '
    '"resource_key": "", "email": "user@example.com"}'
)

# The real pointer form, per the git-LFS pointer-file spec.
