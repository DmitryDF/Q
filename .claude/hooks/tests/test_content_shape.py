def test_the_check_is_wired_at_exactly_one_site():
    """A2's guard rail. The whole reason the check is in the port rather than in
    each adapter is that a per-adapter copy would drift; asserting one call site
    is what keeps that true as adapters are added."""
    port_src = (CONFIG_DIR / "skills" / "research" / "source_port.py").read_text()
    calls = [n for n in ast.walk(ast.parse(port_src))
             if isinstance(n, ast.Call)
             and (getattr(n.func, "id", None) == "not_the_document"
                  or getattr(n.func, "attr", None) == "not_the_document")]
    assert len(calls) == 1, f"expected exactly one call site, found {len(calls)}"

    for module in ("document_folder", "knowledge_library", "code_base", "linear",
                   "web"):
        src = (CONFIG_DIR / "skills" / "research" / "adapters"
               / f"{module}.py").read_text()
        assert "not_the_document" not in src, (
            f"{module} calls the predicate directly; the port owns this decision")


def test_a_non_path_shaped_kind_inherits_nothing_from_this_gate():
    """The gate is what keeps the kind-generic check from colliding with a
    kind-specific one an adapter already owns. `linear` is `path_shaped=False`
    and keeps its own emptiness refusal; a future non-path-shaped kind will need
    its own, and nothing here will remind the implementer — which is why the
    residual is recorded at the call site."""
    assert sp.rules_for("linear").path_shaped is False
    linear_src = (CONFIG_DIR / "skills" / "research" / "adapters"
                  / "linear.py").read_text()
    assert "not_the_document" not in linear_src
    assert "if not content:" in linear_src, (
        "linear's own kind-specific emptiness check was removed")


def test_an_unregistered_kind_inherits_the_gate():
    """`_DEFAULT_KIND_RULES.path_shaped` is True, so a kind with no registered
    rules gets the check with no edit — the Evolution-test half of why A2 places
    this in the port."""
    assert sp.rules_for("a-kind-nobody-registered").path_shaped is True


