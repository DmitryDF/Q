def test_the_real_drive_placeholder_bytes_are_not_the_document():
    """The exact bytes that were driven through the shipped adapter and admitted."""
    assert len(REAL_DRIVE_STUB.encode("utf-8")) < 256, "the real stub is small"
    reason = cs.not_the_document(REAL_DRIVE_STUB)
    assert reason, "the real placeholder was accepted as a document"
    assert "placeholder" in reason


