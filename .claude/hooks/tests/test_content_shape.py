def test_an_lfs_pointer_in_a_real_repository_is_refused_and_real_code_still_reads(repo):
    """Both halves together. `code` only became reachable in production recently
    and an LFS pointer is ordinary text in a working tree, so this is the forward
    risk rather than a live one — which is exactly why it needs a test."""
    result = dr.read_declared_sources(srec.code_scope([repo]), projects_root=repo)

    read = sorted(Path(r.item).name for r in result.readings)
    refused = {Path(r.item).name: r for r in result.refusals}

    assert "auth.py" in read, (
        f"real code stopped reading; refusals were "
        f"{[r.render() for r in result.refusals]}")
    assert "asset.bin" in refused, "an LFS pointer was read as though it were the object"
    assert refused["asset.bin"].obligation == sp.OBLIGATION_READABLE
    assert "LFS" in refused["asset.bin"].reason

    assert "blank.py" in refused, "an empty file in a repository was admitted"
    assert refused["blank.py"].reason == cs.REASON_EMPTY


