@pytest.mark.parametrize("kind", PATH_SHAPED_KINDS)
def test_an_empty_file_is_refused_by_name_through_the_port(kind, folder):
    """The live case, at the altitude that matters. Before this slice the file
    was admitted with `line = "1"` and cited as a source with nothing behind it."""
    root, declared = folder
    empty = declared / "german_care_workforce_PHASE2_RESEARCH.md"
    empty.write_text("")
    scope = _SCOPES[kind]([declared])
    adapter = _ADAPTERS[kind](projects_root=root)

    result = _port().admit(_item(kind, empty), scope, adapter, run_id="r")

    assert not result.admitted, "an empty file was admitted and would be cited"
    assert result.degradation.obligation == sp.OBLIGATION_READABLE
    assert result.degradation.reason == cs.REASON_EMPTY
    assert result.pin is None, "a refused item must carry no pin"
    assert result.content in (None, ""), "a refused item must carry no content"


@pytest.mark.parametrize("kind", PATH_SHAPED_KINDS)
def test_a_placeholder_is_refused_while_its_real_sibling_still_reads(kind, folder):
    """The inversion pair, at port level.

    The census found a real folder where the PDF (the document) is refused by
    name and the placeholder (the pointer) is silently cited. Both halves are
    asserted together on purpose: a predicate that refused everything would pass
    the first assertion alone.
    """
    root, declared = folder
    (declared / "Case_Study.gdoc").write_text(REAL_DRIVE_STUB)
    (declared / "Case_Study.md").write_text("# Case study\n\nThe real thing.\n")
    scope = _SCOPES[kind]([declared])
    adapter = _ADAPTERS[kind](projects_root=root)
    port = _port()

    stub = port.admit(_item(kind, declared / "Case_Study.gdoc"), scope, adapter,
                      run_id="r")
    assert not stub.admitted, "the placeholder was admitted"
    assert stub.degradation.obligation == sp.OBLIGATION_READABLE

    real = port.admit(_item(kind, declared / "Case_Study.md"), scope, adapter,
                      run_id="r")
    assert real.admitted, (
        f"the real sibling was refused too: {real.degradation}")
    assert "The real thing." in real.content


@pytest.mark.parametrize("kind", PATH_SHAPED_KINDS)
def test_the_refusal_is_a_recorded_degradation_not_merely_a_return(kind, folder):
    """`admit()` persists its own outcome before returning. A refusal that were
    only returned would leave no trail for `list_degradations` — the retrieval a
    later slice's integrity accounting reads."""
    root, declared = folder
    (declared / "empty.md").write_text("")
    scope = _SCOPES[kind]([declared])
    adapter = _ADAPTERS[kind](projects_root=root)
    store = arec.InMemoryAdmissionRecordStore()

    sp.AdmissionPort(store).admit(_item(kind, declared / "empty.md"), scope,
                                  adapter, run_id="run-1")

    recorded = store.list_degradations("run-1")
    assert len(recorded) == 1, "the refusal left no record"
    assert recorded[0].obligation == sp.OBLIGATION_READABLE
    assert recorded[0].reason == cs.REASON_EMPTY


