def test_the_refusal_reaches_the_report_body_exactly_as_a_pdf_refusal_does(folder):
    """C3. To a person this is the same event as an unreadable PDF: a file you
    pointed me at could not be read, and here is which one. So it must arrive
    through the same channel, at the same point, wearing the same obligation —
    the assertion is that the two renderings are indistinguishable in shape."""
    root, declared = folder
    (declared / "empty_research.md").write_text("")
    (declared / "scan.pdf").write_bytes(b"%PDF-1.4\n\x80\x81\x82 binary\n")
    (declared / "real.md").write_text("# Real\n\nSomething to find.\n")

    result = dr.read_declared_sources(
        srec.document_folder_scope([declared]), projects_root=root)

    rendered = {Path(r.item).name: r.render() for r in result.refusals}
    assert "empty_research.md" in rendered, (
        f"the empty file was not refused by name; refusals were {rendered}")
    assert "scan.pdf" in rendered, "the PDF control did not refuse"

    empty_line, pdf_line = rendered["empty_research.md"], rendered["scan.pdf"]
    for line in (empty_line, pdf_line):
        assert line.startswith("refused: ")
        assert line.endswith(f"[{sp.OBLIGATION_READABLE}]")

    body = dr.synthesize_from_admissions(result)
    assert "empty_research.md" in body, (
        "the refusal never reached the body, so a person is told nothing")
    assert "Something to find." in body, "the real file stopped reaching the body"


def test_the_person_is_told_what_to_do_about_it(folder):
    """C5. Being told is what lets them act — convert the file, point somewhere
    else, or knowingly accept the gap. A reason naming only the failure would
    satisfy the letter of "loud" and none of its purpose."""
    root, declared = folder
    (declared / "Case_Study.gdoc").write_text(REAL_DRIVE_STUB)

    result = dr.read_declared_sources(
        srec.document_folder_scope([declared]), projects_root=root)

    reasons = " ".join(r.reason for r in result.refusals)
    assert "export or download" in reasons, (
        f"the refusal names no remedy: {reasons}")
