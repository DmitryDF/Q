def test_a_genuine_one_line_note_survives_and_the_cap_is_not_what_saves_it():
    """The load-bearing must-not-refuse case.

    A ~50-byte note is FAR below any cap, so no upper bound could protect it.
    What protects it is that every shape test names a concrete shape.

    The second assertion is the one that bites, and it is not a restatement of
    the first: it calls each `Shape.matches` DIRECTLY, which is downstream of
    the cap, so the cap cannot contribute to the result. If the note survived
    only because `not_the_document` returned early on size, the first assertion
    would still pass and this one would fail.
    """
    assert len(GENUINE_SHORT_NOTE.encode("utf-8")) < 100
    assert cs.not_the_document(GENUINE_SHORT_NOTE) is None

    assert not any(shape.matches(GENUINE_SHORT_NOTE) for shape in cs.SHAPES), (
        "ordinary prose matched a shape signature — the note survives only by "
        "accident of the size cap, which cannot protect it")


def test_a_large_genuine_document_carrying_the_same_key_survives_by_the_cap():
    """The OTHER error direction, guarded by a different mechanism.

    A real JSON document legitimately carrying `doc_id` matches the placeholder
    signature exactly. The cap is what saves it, and nothing else can.
    """
    big = json.dumps({"doc_id": "x", "records": ["y" * 80 for _ in range(200)]})
    assert len(big.encode("utf-8")) > cs.MAX_SHAPE_BYTES
    assert cs.not_the_document(big) is None

    small = json.dumps({"doc_id": "x"})
    assert cs.not_the_document(small), (
        "the cap is the only thing distinguishing these two, so the small one "
        "must be caught or the previous assertion proves nothing")


@pytest.mark.parametrize("text", [
    "# Notes\n\nThe pricing model has three tiers.\n",
    "def login():\n    return True\n",
    "version 3 of the git-lfs migration plan is attached\n",
    "See https://git-lfs.github.com/spec/v1 for the pointer format.\n",
    "The config uses a doc_id field to address each record.\n",
    '["a", "b", "c"]\n',
    "key: value\nother: thing\n",
])
def test_ordinary_content_is_never_refused(text):
    """Prose that MENTIONS a shape is not that shape. The LFS test requires the
    fixed token at the START of the file; the placeholder test requires a JSON
    object rather than a sentence containing the key."""
    assert cs.not_the_document(text) is None, text


def test_the_predicate_never_raises_and_returns_a_reason_or_nothing():
    for text in ["\x00", "{", "{]", "[]", "null", "true", '"a string"',
                 "﻿", "a" * 100000]:
        out = cs.not_the_document(text)
        assert out is None or isinstance(out, str)


# =========================================================================== #
# Predicate level — content, never location (the mirrored design-A31 guard)
# =========================================================================== #

def test_the_predicate_cannot_branch_on_location_because_it_never_sees_one():
    """The structural half. The defect exists because something inferred content
    from location; the strongest available guard is that the function has no
    location to inspect. A path parameter cannot be added without changing this
    signature, so this test fails before any location branch can be written."""
    params = list(inspect.signature(cs.not_the_document).parameters)
    assert params == ["content"], (
        f"not_the_document grew a parameter beyond the text: {params}")


def test_no_location_branch_exists_in_the_predicate_module():
    """The design-A31 AST guard, mirrored onto this module.

    `test_local_file_admission.py` asserts the document-folder adapter contains
    no mount detection and no provider path token, because a branch testing for
    one would make "ordinary" conditional on passing a test. The same must hold
    here: this module recognises SHAPES IN BYTES, and a provider path or a mount
    test would reintroduce exactly the inference the slice removes.
    """
    src = (CONFIG_DIR / "skills" / "research" / "content_shape.py").read_text()
    tree = ast.parse(src)
    for node in ast.walk(tree):
        if isinstance(node, ast.Call):
            name = getattr(node.func, "attr", None) or getattr(node.func, "id", None)
            assert name not in ("is_mount", "is_dir", "is_file", "exists",
                                "stat", "resolve", "expanduser"), (
                f"the predicate inspects the filesystem via {name!r}")

    # The token half scans the WHOLE body, docstrings excluded. The original
    # guard used `split('"""')[-1]`, which returns the text after the LAST
    # triple quote rather than after the module docstring — on this module that
    # was 9 of 190 lines, so a provider list added inside a shape function would
    # have passed untouched. See `_source_guard` for the measurement.
    body = code_without_docstrings(src)
    assert "_is_drive_placeholder" in body, (
        "the scanned body no longer reaches the shape functions, which is where "
        "a location branch would be added — the guard has gone hollow again")
    for token in ("CloudStorage", "GoogleDrive", "Dropbox", "OneDrive",
                  "suffix", "Path", "os.path"):
        assert token not in body, f"the predicate branches on location via {token!r}"


def test_the_catalog_is_extensible_without_touching_the_port():
    """A shape nobody has taught it yet passes unrefused — that is the disclosed
    residue of choosing specificity over guessing. Adding one must be a new row
    here and nothing else, which is what this asserts: the port names no shape."""
    unknown = "PLACEHOLDER-FORMAT-NOBODY-HAS-TAUGHT-THIS-TOOL\nref: 12345\n"
    assert cs.not_the_document(unknown) is None, (
        "an uncatalogued shape was caught — good, but then this test's premise "
        "is stale and the disclosed limit needs rewording")

    port_src = (CONFIG_DIR / "skills" / "research" / "source_port.py").read_text()
    for shape in cs.SHAPES:
        assert shape.name not in port_src, (
            f"the port names the shape {shape.name!r}; adding a shape would "
            "then require touching the port")


